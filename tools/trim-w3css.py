#!/usr/bin/env python3
"""Write hugo/static/css/w3-used.css: w3.css with only the rules the site uses.

The site uses about a dozen of w3.css's classes. This keeps every rule whose
selectors use only those classes, plus every rule with no w3- class at all
(html, body, h1 and other element defaults), and drops the rest, along with
@keyframes that nothing left refers to. w3.css itself is left as it is (the
EPUB export uses it whole).

The classes are found by searching the Hugo layouts, the content, the
site's TypeScript and literature.css for "w3-...". Run it again after using
a w3 class that was not used before:

    python3 tools/trim-w3css.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "hugo/static/css/w3.css"
TARGET = ROOT / "hugo/static/css/w3-used.css"
SEARCH = [ROOT / "hugo/layouts", ROOT / "hugo/content", ROOT / "hugo/static/css/literature.css",
          *[ROOT / "ts" / f"{name}.ts" for name in ("hugo-nav", "reader-settings", "reader-mode", "page-loader")]]
CLASS = re.compile(r"w3-[a-z0-9-]+")


def used_classes() -> set[str]:
    found: set[str] = set()
    for path in SEARCH:
        files = path.rglob("*") if path.is_dir() else [path]
        for file in files:
            if file.is_file():
                found |= set(CLASS.findall(file.read_text(encoding="utf-8", errors="ignore")))
    return found


def blocks(css: str):
    """Top-level (prelude, body) pairs, matching braces."""
    i = 0
    while True:
        start = css.find("{", i)
        if start < 0:
            return
        depth, j = 1, start + 1
        while depth:
            depth += {"{": 1, "}": -1}.get(css[j], 0)
            j += 1
        yield css[i:start].strip(), css[start + 1:j - 1]
        i = j


def split_selectors(prelude: str) -> list[str]:
    parts, depth, current = [], 0, ""
    for char in prelude:
        depth += {"(": 1, ")": -1}.get(char, 0)
        if char == "," and depth == 0:
            parts.append(current)
            current = ""
        else:
            current += char
    return [part.strip() for part in parts + [current] if part.strip()]


def trim(css: str, used: set[str]) -> str:
    out = []
    for prelude, body in blocks(css):
        if prelude.startswith("@media") or prelude.startswith("@supports"):
            inner = trim(body, used)
            if inner:
                out.append(f"{prelude}{{{inner}}}")
        elif prelude.startswith("@"):
            out.append(f"{prelude}{{{body}}}")
        else:
            keep = [s for s in split_selectors(prelude) if set(CLASS.findall(s)) <= used]
            if keep:
                out.append(f"{','.join(keep)}{{{body}}}")
    return "\n".join(out)


def drop_unused_keyframes(css: str) -> str:
    rest = re.sub(r"@(-webkit-)?keyframes\s+[\w-]+\s*\{(?:[^{}]*\{[^{}]*\})*[^{}]*\}", "", css)
    def keep(match: re.Match) -> str:
        return match.group(0) if re.search(rf"\b{re.escape(match.group(2))}\b", rest) else ""
    return re.sub(r"@(-webkit-)?keyframes\s+([\w-]+)\s*\{(?:[^{}]*\{[^{}]*\})*[^{}]*\}", keep, css)


def main() -> None:
    css = SOURCE.read_text(encoding="utf-8-sig")
    header = css[:css.find("*/") + 2] if css.lstrip().startswith("/*") else ""
    body = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    used = used_classes()
    result = drop_unused_keyframes(trim(body, used))
    TARGET.write_text(
        f"{header}\n/* Generated by tools/trim-w3css.py from w3.css: only the rules for the\n"
        f"   classes the site uses ({', '.join(sorted(used))}). Do not edit; run the script. */\n"
        f"{result}\n", encoding="utf-8")
    print(f"{TARGET.relative_to(ROOT)}: {len(result)} of {len(body)} characters, {len(used)} classes", file=sys.stderr)


if __name__ == "__main__":
    main()
